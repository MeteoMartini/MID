import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const paths=['ci/github/workflows/install-mid.yml','.github/workflows/install-mid.yml','workflow-patches/install-mid.yml'];
const sources=await Promise.all(paths.map(p=>readFile(new URL('../'+p,import.meta.url),'utf8')));
for(const source of sources)assert.equal(source,sources[0],'Installer mirrors must be byte-identical.');
const source=sources[0],job=source.split('  install_build:')[1].split('\n  worker_deploy:')[0];
assert.equal(Number(job.match(/^    timeout-minutes: (\d+)$/m)?.[1]),40);
const step=source.split('      - name: Produktionsbuild und Regressionstests ausführen')[1].split('\n      - name:')[0];
assert.equal(Number(step.match(/timeout-minutes: (\d+)/)?.[1]),25);
assert.match(step,/set -euo pipefail\s+ npm run verify/);
assert.doesNotMatch(step,/continue-on-error|MID_REGRESSION_SHARD|MID_REGRESSION_SKIP|\|\|\s*true/);
assert.match(source,/Geprüften Web-Build in die Capacitor-iOS-Hülle übernehmen/);
assert.match(source,/Erfolgreichen Pages-\/Worker-Release finalisieren/);
console.log('Installer budget bounded; full verification, mirrors and downstream gates preserved.');
