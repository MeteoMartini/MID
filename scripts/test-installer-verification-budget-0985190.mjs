import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const paths=['ci/github/workflows/install-mid.yml','.github/workflows/install-mid.yml','workflow-patches/install-mid.yml'];
const sources=await Promise.all(paths.map(p=>readFile(new URL('../'+p,import.meta.url),'utf8')));
for(const source of sources)assert.equal(source,sources[0],'Installer mirrors must be byte-identical.');
const source=sources[0],job=source.split('  install_build:')[1].split('\n  deploy_worker:')[0];
assert.equal(Number(job.match(/^    timeout-minutes: (\d+)$/m)?.[1]),40);
const step=source.split('      - name: Produktionsbuild und Worker-Syntax verifizieren')[1].split('\n      - name:')[0];
assert.equal(Number(step.match(/timeout-minutes: (\d+)/)?.[1]),8);
assert.match(step,/set -euo pipefail\s+ npm run build\s+ node --check worker\/metar-proxy\.js/);
assert.doesNotMatch(step,/continue-on-error|MID_REGRESSION_SKIP|\|\|\s*true/);
const core=source.split('  verify_core_shards:')[1].split('  verify_heavy:')[0];
assert.match(core,/fail-fast: false/);
assert.match(core,/MID_REGRESSION_SHARD: \$\{\{ matrix\.shard \}\}/);
assert.match(core,/npm run test:regressions/);
assert.equal((core.match(/shard: core-[1-4]\/4/g)||[]).length,4,'Every Core shard must run.');
assert.doesNotMatch(core,/continue-on-error|MID_REGRESSION_SKIP|\|\|\s*true/);
assert.match(source,/needs: \[prepare_release, verify_core, verify_core_shards, verify_heavy\]/);
assert.match(source,/needs\.verify_core_shards\.result == 'success'/);
assert.match(source,/fail-fast: false/);
for(const shard of ['heavy-native-map','heavy-unified-map','heavy-mountain-visual'])assert.ok(source.includes(shard));
assert.match(source,/Geprüften Web-Build in die Capacitor-iOS-Hülle übernehmen/);
assert.match(source,/Erfolgreichen Pages-\/Worker-Release finalisieren/);
console.log('Installer budget bounded; full verification, mirrors and downstream gates preserved.');
