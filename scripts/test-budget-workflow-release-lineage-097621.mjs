import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url),read=file=>readFile(new URL(file,root),'utf8');
const pkg=JSON.parse(await read('package.json'));
const baseline=JSON.parse(await read('MID_BASELINE.json'));
const perf=JSON.parse(await read('MID_PERFORMANCE_BASELINE.json'));
const workflow=await read('ci/github/workflows/install-mid.yml');
const changelog=await read('CHANGELOG.md');
assert.equal(pkg.version,baseline.releaseVersion,'Releaseversion und Baseline müssen identisch sein.');
assert.ok(changelog.includes('# v0.9.76.21'),'Korrekturrelease v0.9.76.21 muss dokumentiert sein.');
const parallelTest='scripts/test-weather-profile-cell-gaps-day-wind-pin-097620.mjs';
assert.equal(pkg.scripts?.['test:weather-profile-cell-gaps-day-wind-pin'],`node ${parallelTest}`,'Parallel übernommener UI-Test muss als gezielter npm-Test erhalten bleiben.');
for(const key of ['requiredRegressionTests','regressionTests','requiredFiles'])assert.ok(baseline[key]?.includes(parallelTest),`${parallelTest} fehlt nach der Parallelkonsolidierung in ${key}.`);
assert.equal(perf.schema,2,'Der getrennte Medien-/Code-Budgetvertrag muss aktiv sein.');
assert.equal(perf.limits.compressibleGzipBytes,5200000);
assert.equal(perf.limits.staticMediaBytes,7000000);
assert.equal(perf.limits.totalGzipBytes,8500000);
assert.ok(!workflow.includes('push --force origin HEAD:refs/heads/mid-stable'),'Stable-Promotion darf keinen Force-Push enthalten.');
assert.ok(workflow.includes("context': 'MID / release-candidate-quality'"));
assert.ok(workflow.includes('git merge-base --is-ancestor "$stable_before" "$release_sha"'));
assert.ok(workflow.includes('push origin "${release_sha}:refs/heads/mid-stable"'));
console.log(`Korrekturrelease v${pkg.version}: Budgetvertrag und Fast-Forward-Stable-Promotion sind konsistent.`);
