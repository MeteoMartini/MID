import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const app=readFileSync(new URL('../src/App.tsx',import.meta.url),'utf8');
const css=readFileSync(new URL('../src/styles.css',import.meta.url),'utf8');
assert.match(app,/FORECAST_DISPLAY_SETTINGS_KEY='mid:forecastDisplaySettings'/,'eigener persistenter Einstellungsbereich fehlt');
assert.match(app,/showSevenDaySummary:parsed\?\.showSevenDaySummary!==false/,'Kurzinterpretation muss standardmäßig aktiv sein');
assert.match(app,/7-Tage-Kurzinterpretation/,'Schalter in den Einstellungen fehlt');
assert.match(app,/function buildSevenDayForecastSummary/,'Auswertungsfunktion fehlt');
assert.match(app,/function sevenDayPoint/,'Tagescharakter-Auswertung für die Kurzinterpretation fehlt');
assert.match(app,/function sevenDayClause/,'natürliche Satzbildung für die Kurzinterpretation fehlt');
assert.match(app,/Heute und morgen \$\{description\}|Heute \$\{description\}/,'der erste Prognosetag muss sprachlich natürlich mit Heute beginnen können');
assert.match(app,/zunehmend heiß|sehr heiß|extrem heiß|sommerlich warm/,'DWD-nahe Temperaturklassifikation fehlt');
assert.match(app,/überwiegend bewölkt, aber meist trocken/,'bewölkte Trockenphasen müssen im Trend eigenständig erkennbar sein');
const summaryIndex=app.indexOf('<SevenDayForecastSummary');
const dayIndex=app.indexOf('{forecastDays.map',summaryIndex);
assert.ok(summaryIndex>=0&&dayIndex>summaryIndex,'Kurzinterpretation muss vor dem ersten Prognosetag stehen');
assert.match(css,/\.seven-day-forecast-summary/,'Gestaltung der Kurzinterpretation fehlt');
assert.match(app,/compactLandscape/,'Querformat-Erkennung fehlt');
assert.match(app,/showAllDetailMarkers=narrowChart\|\|compactLandscape/,'Querformat muss alle Detailmarker aktivieren');
assert.match(app,/if\(showAllDetailMarkers\)\{iconPoints\.length=0;iconPoints\.push\(\.\.\.representativeDetailPictograms\(p\.map/,'alle Wetterpiktogramme müssen im Querformat erhalten bleiben');
assert.match(app,/directionStep=showAllDetailMarkers\?1/,'alle Windrichtungspfeile müssen im Querformat erhalten bleiben');
console.log('7-Tage-Kurzinterpretation und vollständige Querformatmarker geprüft.');
