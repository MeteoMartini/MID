import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createWidgetNetworkDiagnostics} from '../tools/widget-export/network-diagnostics.mjs';

const network=createWidgetNetworkDiagnostics();
const request=(id,url,timestamp=1)=>network.observe('Network.requestWillBeSent',{requestId:id,timestamp,request:{url}});
const response=(id,status,timestamp=2)=>network.observe('Network.responseReceived',{requestId:id,timestamp,response:{status}});
const finished=(id,timestamp=3)=>network.observe('Network.loadingFinished',{requestId:id,timestamp});
const failed=(id,errorText,timestamp=4,extras={})=>network.observe('Network.loadingFailed',{requestId:id,timestamp,errorText,...extras});
const secret='token-should-never-appear-in-diagnostics';
request('one',`https://api.open-meteo.com/v1/forecast?latitude=50.1234&longitude=7.1234&apikey=${secret}`);
response('one',429);finished('one');
request('two',`https://www.midwx.app/api/mid-worker?secret=${secret}`,3);
response('two',504,4);failed('two','net::ERR_TIMED_OUT',5);
request('three',`https://opendata.dwd.de/weather/nwp?auth=${secret}`,5);
failed('three','net::ERR_NAME_NOT_RESOLVED',6);
request('four',`https://user:password@private.example/secret/${secret}`,6);
failed('four','net::ERR_ABORTED',7,{canceled:true});
request('five','data:text/html,private',7);finished('five',7);
network.observe('Network.loadingFailed',{requestId:'unobserved',timestamp:8,errorText:`potentially sensitive ${secret}`});
const snapshot=network.snapshot(),encoded=JSON.stringify(snapshot);
assert.equal(snapshot.schema,1);
assert.equal(snapshot.captureWindow,'network-enabled-before-navigation');
assert.equal(snapshot.observedRequests,5);
assert.equal(snapshot.orphanEvents,1);
assert.equal(snapshot.groups['open-meteo'].status['rate-limited'],1);
assert.equal(snapshot.groups['open-meteo'].completed,1);
assert.equal(snapshot.groups['mid-origin'].status['5xx'],1);
assert.equal(snapshot.groups['mid-origin'].errors['network-timeout'],1);
assert.equal(snapshot.groups.dwd.errors.dns,1);
assert.equal(snapshot.groups.external.errors.canceled,1);
assert.equal(snapshot.groups['non-http'].completed,1);
assert.equal(snapshot.groups['open-meteo'].maxDurationMs,2000);
for(const marker of [secret,'latitude','longitude','apikey','password','private.example','/api/mid-worker','requestId','errorText','headers','cookies'])assert.ok(!encoded.includes(marker),`Sensitive network field leaked: ${marker}`);
const bounded=createWidgetNetworkDiagnostics({limit:2});
for(let i=0;i<3;i++)bounded.observe('Network.requestWillBeSent',{requestId:String(i),timestamp:i,request:{url:'https://www.midwx.app/'}});
assert.equal(bounded.snapshot().truncated,true);
assert.equal(bounded.snapshot().groups['mid-origin'].pending,2);
bounded.observe('Network.loadingFinished',{requestId:'0',timestamp:3});
assert.equal(bounded.snapshot().groups['mid-origin'].completed,1);
const redirect=createWidgetNetworkDiagnostics();
redirect.observe('Network.requestWillBeSent',{requestId:'r',timestamp:1,request:{url:'https://www.midwx.app/a'}});
redirect.observe('Network.requestWillBeSent',{requestId:'r',timestamp:2,request:{url:'https://api.open-meteo.com/v1'},redirectResponse:{status:302}});
redirect.observe('Network.responseReceived',{requestId:'r',timestamp:3,response:{status:200}});
redirect.observe('Network.loadingFinished',{requestId:'r',timestamp:4});
assert.equal(redirect.snapshot().groups['mid-origin'].status['3xx'],1);
assert.equal(redirect.snapshot().groups['mid-origin'].pending,0);
assert.equal(redirect.snapshot().groups['open-meteo'].completed,1);
const source=await readFile(new URL('../tools/widget-export/capture-widget.mjs',import.meta.url),'utf8');
for(const token of ["browserArgs.push('about:blank')","createWidgetNetworkDiagnostics()","Page.navigate',{url:url.toString()}","message.method.startsWith('Network.')","network:networkDiagnostics.snapshot()"])assert.ok(source.includes(token),`Widget-Capture-Trace-Pfad fehlt: ${token}`);
assert.ok(source.indexOf("await cdp.call('Network.enable')")<source.indexOf("await cdp.call('Page.navigate'"),'Network monitoring must start before navigation');
assert.ok(!source.includes('networkFailures:failures'),'Raw network errors may not appear in reports');
console.log('Widget-CDP: 5 real event patterns, redirects, pending, truncation, status, rate limits, DNS, timeout, canceled, and no URL/token/coordinate leakage.');
