import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {regressionSuite} from './regression-suite.mjs';
import {regressionShardPlan,regressionCoreSubshards} from './regression-shards.mjs';
import {mapBrowserRunPlan,mapBrowserCases,mapBrowserMemoryProbe} from './map-browser-shards.mjs';

const root=new URL('../',import.meta.url),read=p=>readFile(new URL(p,root),'utf8');
const canonical=await read('ci/github/workflows/mid-code-revision.yml');
assert.equal(canonical,await read('.github/workflows/mid-code-revision.yml'),'Source and active revision workflows must remain exactly identical');
assert.doesNotMatch(canonical,/^  install:\s*$/m,'Obsoleter Revision-Installerjob darf nicht zurückkehren');
assert.doesNotMatch(canonical,/^          - install\s*$/m,'Veralteter task=install-Dispatch muss dauerhaft entfallen');
assert.doesNotMatch(canonical,/git push origin HEAD:(?:main|mid-stable)/,'Revision darf geschützte Release-Branches nie direkt beschreiben');
const matrix=canonical.split('  revision_regressions:')[1]?.split('  ci:')[0];
const resolver=canonical.split('  revision_source:')[1]?.split('  revision_regressions:')[0];
const ci=canonical.split('  ci:')[1]?.split('  nightly:')[0];
const nightly=canonical.split('  nightly:')[1]?.split('  health:')[0];
assert.ok(matrix&&resolver&&ci&&nightly,'All mandatory revision stages must exist');
const expected=['core-1/4','core-2/4','core-3/4','core-4/4','heavy-browser-state','heavy-native-map','heavy-mountain-visual','heavy-unified-map@1/3','heavy-unified-map@2/3','heavy-unified-map@3/3'];
const actual=[...matrix.matchAll(/^\s+- \{shard: '([^']+)', map_group: '([^']*)'\}$/gm)].map(m=>m[1]+(m[2]?'@'+m[2]:''));
assert.deepEqual(actual,expected,'Exactly 4 separate Core shards, 3 Heavy specials and 3 split map groups must be required');
assert.match(matrix,/fail-fast: false/,'Failing a shard must not cancel untested mandatory cases');
assert.doesNotMatch(matrix,/continue-on-error:/,'No weakened or best-effort shard');
assert.match(matrix,/MID_REGRESSION_SHARD: \$\{\{ matrix\.shard \}\}/);
assert.match(matrix,/MID_MAP_QA_SHARD: \$\{\{ matrix\.map_group \}\}/);
assert.match(matrix,/ref: \$\{\{ needs\.revision_source\.outputs\.sha \}\}/);
assert.match(matrix,/run: npm run build/);
assert.match(matrix,/run: npm run test:regressions/);
assert.match(matrix,/run: node scripts\/test-regression-sharding-0985171\.mjs/);
assert.match(matrix,/node scripts\/prepare-browser-runtimes\.mjs/);
assert.match(matrix,/npm ci --no-audit --no-fund --prefer-offline --legacy-peer-deps/);
assert.match(matrix,/permissions:\n\s+contents: read/);
assert.doesNotMatch(matrix,/secrets\.|contents: write|actions: write|id-token: write|MID_RELEASE_APP_PRIVATE_KEY/);
assert.match(resolver,/if \[ "\$GITHUB_EVENT_NAME" = pull_request \]/);
assert.match(resolver,/git\/ref\/heads\/mid-stable/);
assert.match(resolver,/git\/ref\/heads\/main/);
assert.match(resolver,/test "\$stable" = "\$main"/);
assert.match(resolver,/test "\$GITHUB_SHA" = "\$stable"/);
assert.match(resolver,/echo "sha=\$sha" >> "\$GITHUB_OUTPUT"/);
for(const section of [ci,nightly]){
 assert.match(section,/needs: \[revision_source, revision_regressions\]/);
 assert.match(section,/always\(\) &&/,'Failed dependent regression jobs must be visibly rejected, not silently skip the final checks');
 assert.match(section,/SOURCE_RESULT: \$\{\{ needs\.revision_source\.result \}\}/);
 assert.match(section,/MATRIX_RESULT: \$\{\{ needs\.revision_regressions\.result \}\}/);
 assert.match(section,/test "\$SOURCE_RESULT" = success && test "\$MATRIX_RESULT" = success/);
 assert.match(section,/run: \|[\s\S]{0,240}npm run build/,'Final stage still performs independent production build');
 assert.doesNotMatch(section,/run: npm run verify/,'No second sequential 1056-test execution after mandatory matrix');
}
assert.match(nightly,/steps\.verify\.outcome != 'success'/,'Nightly must report a failed matrix as a real failure');
assert.match(ci,/run: npm run audit:dependencies/);
assert.match(nightly,/run: npm run audit:all/);
const all=await regressionSuite(new URL('../',import.meta.url).pathname);
const plan=await regressionShardPlan(new URL('../',import.meta.url).pathname);
const cores=regressionCoreSubshards(plan.shards.core);
const assigned=[...Object.values(cores).flat(),...['heavy-browser-state','heavy-native-map','heavy-mountain-visual','heavy-unified-map'].flatMap(k=>plan.shards[k])];
assert.equal(assigned.length,all.length);
assert.equal(new Set(assigned).size,all.length);
assert.deepEqual(new Set(assigned),new Set(all));
for(const name of ['core-1/4','core-2/4','core-3/4','core-4/4'])assert.ok(cores[name].length>0);
const mapCases=mapBrowserRunPlan().flatMap(group=>mapBrowserCases(group));
assert.equal(mapCases.length,24);
assert.equal(new Set(mapCases.map(v=>JSON.stringify(v))).size,24);
assert.equal(mapBrowserMemoryProbe('1/3'),false);
assert.equal(mapBrowserMemoryProbe('2/3'),true);
assert.equal(mapBrowserMemoryProbe('3/3'),false);
assert.throws(()=>mapBrowserRunPlan('4/3'));
console.log('MID revision matrix: 10 SHA-identical jobs; all regression files and 24 browser cases exactly covered; strict CI/nightly gates remain.');
