import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {collectMapMemorySample,profileMapCycles,summarizeMapMemory} from './lib/mapMemoryProfile.mjs';
const calls=[];let samples=0,cycles=0;
const session={async send(method){calls.push(method);if(method==='HeapProfiler.collectGarbage')return {};
  if(method==='Runtime.getHeapUsage')return {usedSize:100+(samples++)*10,totalSize:500,backingStorageSize:20};
  if(method==='Memory.getDOMCounters')return {documents:1,nodes:80,jsEventListeners:12};
  throw Error('Unexpected command');}};
const report=await profileMapCycles(session,async()=>{cycles++;});
assert.equal(cycles,22);assert.deepEqual(report.samples.map(s=>s.cycle),[0,5,10,15,20]);
assert.equal(report.completedCycles,20);assert.equal(report.heapDeltaBytes,40);assert.equal(report.heapDeltaPercent,40);
assert.equal(report.strictlyIncreasingHeap,true);assert.equal(report.nodeDelta,0);assert.equal(report.listenerDelta,0);
assert.deepEqual(calls.slice(0,3),['HeapProfiler.collectGarbage','Runtime.getHeapUsage','Memory.getDOMCounters']);
const decreasing=report.samples.map((s,i)=>({...s,usedHeapBytes:200-i*10}));
assert.equal(summarizeMapMemory(decreasing,[10,20]).heapDeltaBytes,-40);
assert.equal(summarizeMapMemory(decreasing,[10,20]).strictlyIncreasingHeap,false);
assert.throws(()=>summarizeMapMemory([],[]));
assert.throws(()=>summarizeMapMemory([report.samples[0],report.samples[0]],[]));
await assert.rejects(()=>collectMapMemorySample({send:async()=>({usedSize:NaN,totalSize:1})},0),/Invalid Chromium/);
await assert.rejects(()=>collectMapMemorySample({send:async()=>{throw Error('CDP failed')}},0),/CDP failed/);
await assert.rejects(()=>profileMapCycles(session,async()=>{throw Error('model failed')}),/model failed/);
const qa=readFileSync(new URL('./verify-unified-map-browser-0985167.mjs',import.meta.url),'utf8');
for(const token of ['profileMapCycles','newCDPSession','startTracing','stopTracing','isolated-memory-cycles'])assert.ok(qa.includes(token),token);
const baseline=JSON.parse(readFileSync(new URL('../MID_BASELINE.json',import.meta.url)));
for(const key of ['requiredRegressionTests','regressionTests'])assert.ok(baseline[key].includes('scripts/test-map-memory-profile-0985214.mjs'));
console.log('MID .214: isolated 20-cycle post-GC memory measurement, missing/error handling and QA wiring verified');
