import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),ts=require('typescript-strada');
const src=readFileSync(new URL('../src/weather-src/30-ensemble-climate-hazards.tsfrag',import.meta.url),'utf8');
const generated=readFileSync(new URL('../src/weather.ts',import.meta.url),'utf8');
for(const txt of [src,generated])assert.ok(!txt.includes('filterScenarioRainOutliers')&&!txt.includes('cluster.probability>=6'),'Extremmember dürfen nicht verschwinden');
const a=src.indexOf('type ScenarioTrajectory='),b=src.indexOf('function parseModelMembers(',a);
assert.ok(a>=0&&b>a);
const js=ts.transpileModule(src.slice(a,b),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const q=(values,p)=>{const sorted=[...values].sort((a,b)=>a-b);return sorted[Math.round((sorted.length-1)*p)];};
const build=new Function('exports','formatDecimal','quantile',js+'\nreturn buildEnsembleScenarios;')({},x=>String(Number(x).toFixed(1)),q);
const dates=Array.from({length:7},(_,i)=>'2026-10-'+String(i+1).padStart(2,'0'));
const days=dates.map(date=>({date,maxMean:20,minMean:10,precipitationMean:1,modelSummaries:[]}));
const members=new Map(Array.from({length:42},(_,index)=>['member'+String(index).padStart(2,'0'),dates.map(date=>({date,max:20,min:10,precipitation:index<28?0:index<40?3:320,gust:12,sunshineDuration:3000}))]));
const clusters=build([{model:{id:'ifs_test',independenceGroup:'ecmwf',family:'ifs',label:'IFS-Test',resolutionKm:9},members}],days);
assert.ok(clusters.length>=2,'Szenarien existieren');
assert.equal(clusters.reduce((sum,row)=>sum+row.memberCount,0),42,'Alle Member bleiben enthalten');
assert.ok(Math.abs(clusters.reduce((sum,row)=>sum+row.probability,0)-100)<1e-7);
assert.ok(clusters.some(row=>row.probability<6),'Seltenes Extrem erscheint');
assert.ok(Math.max(...clusters.flatMap(row=>row.points.map(point=>point.precipitation)))>=300,'Extrem nicht geglättet/verloren');
console.log('P1 Ensemble: seltene Extremverläufe und 100%-Memberabdeckung verifiziert.');
