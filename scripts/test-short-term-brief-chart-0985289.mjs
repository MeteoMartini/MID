import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {readFile,mkdtemp,rm} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const temp=await mkdtemp(join(tmpdir(),'mid-brief-chart-'));
try{
 const output=join(temp,'brief.cjs');
 await build({entryPoints:['src/shortTermSignificantBrief.ts'],bundle:true,platform:'node',format:'cjs',outfile:output,logLevel:'silent'});
 const {shortTermSignificantBrief:brief}=createRequire(import.meta.url)(output);
 const base=Date.parse('2026-10-18T16:00:00Z'),t=n=>base+n*3600000;
 const f={from:e=>`ab ${new Date(e).toISOString().slice(11,16)} UTC`,at:e=>`um ${new Date(e).toISOString().slice(11,16)} UTC`,gust:n=>`${Math.round(n)} kt`};
 const p=(h,amount,gust=14,label='Leichter Regen')=>({epoch:t(h),precipitationIntervalStartEpoch:t(h),precipitationIntervalEndEpoch:t(h+1),precipitation:amount,gust,weatherLabel:label});
 assert.match(brief([p(0,.3),p(1,0),p(2,0)],t(-.5),f),/ab 16:00 UTC/);
 assert.doesNotMatch(brief([p(0,.3),p(1,0)],t(-.5),f),/14 kt/);
 assert.match(brief([p(0,0),p(1,.3),p(2,0)],t(-.5),f),/ab 17:00 UTC/);
 assert.match(brief([p(0,.3),p(1,0),p(2,0)],t(-.5),f),/Ende etwa um 17:00 UTC/);
 assert.doesNotMatch(brief([p(0,.3),p(1,NaN),p(2,0)],t(-.5),f),/Ende/);
 assert.match(brief([p(0,.3,34),p(1,0,12)],t(-.5),f),/Markante Böen bis 34 kt um 16:00 UTC/);
 assert.doesNotMatch(brief([p(0,.3,26),p(1,0)],t(-.5),f),/Markante/);
 assert.match(brief([p(0,.3,28),p(1,0)],t(-.5),f),/Markante/);
 assert.match(brief([p(0,.3)],t(.2),f),/zunächst/);
 assert.equal(brief([p(0,0),p(1,0)],t(-.5),f),'Keine markanten Wetterereignisse in den nächsten 24 Stunden.');
 assert.equal(brief([p(0,NaN,NaN)],t(-.5),f),'Kurzfristdaten unvollständig.');
 assert.doesNotMatch(brief([p(0,.5)],t(-.5),f),/16:15/);
 const berlin=new Intl.DateTimeFormat('de-DE',{timeZone:'Europe/Berlin',hour:'2-digit',minute:'2-digit',timeZoneName:'shortOffset'}),zone={from:e=>`ab ${berlin.format(e)}`,at:e=>`um ${berlin.format(e)}`,gust:n=>`${Math.round(n)} kt`};
 const repeat=Date.parse('2026-10-25T00:00:00Z'),samples=[{epoch:repeat,precipitation:0,gust:28,weatherLabel:'Trocken'},{epoch:repeat+3600000,precipitation:0,gust:34,weatherLabel:'Trocken'}];
 assert.match(brief(samples,repeat-60000,zone),/34 kt um 02:00 GMT\+1/);
 const spring=Date.parse('2026-03-29T00:00:00Z');
 assert.match(brief([{epoch:spring+3600000,precipitation:.5,gust:0,weatherLabel:'Regen'}],spring,zone),/03:00 GMT\+2/);
 assert.doesNotMatch(brief([p(0,.6),p(1,0)],t(1.1),f),/Leichter Regen/);
 const cockpit=await readFile('src/ForecastCockpit.tsx','utf8'),css=await readFile('src/mapCanvasResponsive.css','utf8');
 assert.ok(cockpit.includes('shortTermPointSummary(profileDisplayPoints')&&cockpit.includes('shortTermSignificantBrief(points'),'Brief must use same chart series');
 assert.ok(!cockpit.includes('const nativeOnset=quarters.find('),'No distinct hidden 15-min onset');
 assert.ok(css.includes('.unified-weather-map .composite-map-status>span'),'Mobile map badge stays one line');
 assert.ok(css.includes('.radarlegend.compact.collapsed'),'Mobile legend is a compact chip');
 assert.ok(!css.includes('.leaflet-control-attribution{display:none'),'Attribution must remain visible');
 console.log('MID C39: 15 event/timing cases and map source protections passed.');
}finally{await rm(temp,{recursive:true,force:true})}
