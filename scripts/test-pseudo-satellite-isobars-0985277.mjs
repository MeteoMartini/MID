import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {readFileSync,mkdtempSync,rmSync} from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const read=p=>readFileSync(p,'utf8');
const tmp=mkdtempSync(path.resolve('.mid-pseudosat-isobars-'));
try{
 const unified=read('src/UnifiedWeatherMap.tsx'),native=read('src/NativeModelMap.tsx'),radar=read('src/RadarPanel.tsx');
 const values=read('src/cloudWeatherData.ts'),exportCode=read('src/cloudWeatherExport.ts');
 assert.ok(unified.includes('const forecastOverlay=isCloudWeather&&settings.enabled'),'Only active model-cloud layers enter the forecast-only overlay');
 assert.ok(unified.includes('unified={{controls,overlay,forecastOverlay,times'),'Keep favorites and map center in persistent overlay');
 assert.ok(radar.includes('{unified?.overlay}{modelAtSelectedTime&&unified?.forecastOverlay}'),'Forecast cloud only on model frames; favorites remain always available');
 assert.ok(radar.includes('unified.enabled?unified.times.map('),'Disabled model layer must not advertise extra forecast frames');
 assert.ok(radar.includes('showRadar&&showSatellite?'),'Mixed satellite and radar observations must identify both sources');
 assert.ok(unified.includes("modelLabel+' · Modell-Wolkenbild (schematisch)'"));
 assert.ok(unified.includes("cloudWeather.ready&&cloudWeather.data?.run===catalog?.index.run"));
 assert.ok(unified.includes("modelId==='icon-d2'&&cloudIsobars"));
 assert.ok(unified.includes("value.run===catalog.index.run&&value.time===cloudPressureTime"));
 assert.ok(unified.includes('linesActive?pressureContours?.isobars??[]:[]'));
 assert.ok(native.includes("kind==='sigwx'&&combined&&cloudIsobars&&pressureContours?.run===combined.run&&pressureContours.time===combined.time"));
 assert.ok(native.includes('cloudRenderMode,cloudContours'));
 assert.ok(values.includes('CLOUD_WEATHER_ISOBARS_KEY'));
 assert.ok(values.includes('writeCloudWeatherIsobars(enabled:boolean)'));
 assert.ok(exportCode.includes('cloudWeatherSvg(data,raster,places,geography.states,mode,isobars)'));
 await build({entryPoints:['src/CompositeTimeline.ts'],outfile:path.join(tmp,'timeline.mjs'),bundle:true,platform:'node',format:'esm',packages:'external',logLevel:'silent'});
 const timeline=await import(pathToFileURL(path.join(tmp,'timeline.mjs')));
 const ref=Date.parse('2026-10-16T12:00:00Z')/1000;
 const f=timeline.buildAvailableCompositeTimeline(ref,{source:'MID',phaseSources:{observation:'EUMETSAT · Messung',forecast:'ICON-D2 · Modell-Wolkenbild (schematisch)'},observations:[ref-300],forecasts:[ref+600]},30,30);
 assert.equal(f.length,2,'No synthetic intermediate satellite/model frames');
 assert.equal(f[0].phase,'observation');assert.equal(f[1].phase,'forecast');
 assert.match(f[0].source,/Messung/);assert.match(f[1].source,/Modell-Wolkenbild/);
 await build({entryPoints:['src/cloudWeatherExport.ts'],outfile:path.join(tmp,'export.mjs'),bundle:true,platform:'node',format:'esm',packages:'external',logLevel:'silent'});
 const e=await import(pathToFileURL(path.join(tmp,'export.mjs')));
 const frame={model:'icon-d2',run:'2026-10-16T00:00:00Z',time:'2026-10-16T12:00:00Z',lats:[48,49],lons:[7,8],cloud:[0,50,95,null],weather:[0,61,71,null]};
 const contour=[{level:1016,paths:[[[48.2,7.2],[48.4,7.4],[48.6,7.6]]]}];
 const plain=e.cloudWeatherSvg(frame,'data:image/png;base64,AA==',[],[],'pseudo');
 const outlined=e.cloudWeatherSvg(frame,'data:image/png;base64,AA==',[],[],'pseudo',contour);
 assert.doesNotMatch(plain,/MSLP-Isobaren/);assert.doesNotMatch(plain,/DWD ICON-D2 MSLP Isobaren/);
 assert.match(outlined,/MSLP-Isobaren \(hPa\)/);assert.match(outlined,/DWD ICON-D2 MSLP Isobaren hPa/);
 assert.match(outlined,/Schematische Modellwolken/);
 assert.equal((outlined.match(/DWD ICON-D2 MSLP Isobaren/g)||[]).length,1);
 console.log('MID v0.9.85.277: observed/model-only phases, identical MSLP run/time gating, shared isobar setting and PNG/SVG provenance passed.');
}finally{rmSync(tmp,{recursive:true,force:true})}
