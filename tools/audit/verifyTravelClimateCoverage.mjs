import assert from 'node:assert/strict';
import {assessTravelFieldCoverage as cover,assessTravelClimateYears as years} from './travelClimateCoverageEvidence.ts';
let n=0;
const t=(condition, label)=>{assert.ok(condition,label);n++;};
const c=cover([20,Number.NaN],'temperature');
t(c.completeMean===null&&c.observedMean===20&&c.valid===1&&c.total===2,'partial temperature cannot claim 10 deg');
const r=cover([2,Number.NaN],'nonnegative');
t(r.completeSum===null&&r.observedMean===2,'partial rain not full amount');
const zero=cover([0,0],'nonnegative');
t(zero.completeSum===0&&zero.status==='complete','zero genuine');
t(cover([2000,0],'nonnegative').completeSum===2000,'extreme unfiltered');
t(cover([-999,2],'nonnegative').completeSum===null,'negative missing indicator not precipitation');
t(cover([null,'0',false,0],'nonnegative').valid===1,'no coercion of null strings or booleans');
t(cover(JSON.parse(JSON.stringify([Number.NaN,0])),'nonnegative').valid===1,'JSON NaN=>null roundtrip');
t(cover([101,99],'probability').status==='partial','PoP range');
t(cover([null,null],'wmo-code').status==='missing','no default overcast code');
t(cover([99,0],'wmo-code').status==='complete','genuine WMO codes');
t(cover([0,3],'wmo-code').completeMean===null && cover([0,3],'wmo-code').completeSum===null,'WMO categories are not arithmetic quantities');
const twenty=years(Array.from({length:20},(_,i)=>({year:1991+i,value:0})),'nonnegative');
t(twenty.status==='sufficient'&&!twenty.complete&&twenty.validYears===20,'20/30 explicit coverage');
const duplicate=years([...Array.from({length:20},(_,i)=>({year:1991+i,value:1})),{year:1991,value:1}],'nonnegative');
t(duplicate.status==='insufficient'&&duplicate.conflictingYears===1,'duplicate year cannot inflate reference');
t(years([{year:1991,value:null},{year:1992,value:-999}],'nonnegative').referenceMean===null,'invalid reference insufficient');
const feb29=years(Array.from({length:8},(_,i)=>({year:1992+i*4,value:1})),'nonnegative');
t(feb29.status==='insufficient'&&feb29.validYears===8,'Feb 29 requires labelled interpolation');
console.log(n+'/'+n+' MID Audit 1.5 pure coverage smoke checks passed');
