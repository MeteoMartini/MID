"""Generate isolated synthetic transport fixtures; never read or rewrite RUC runs."""
import json,hashlib
from pathlib import Path
from lossless_codec_pilot import encode_candidate
ROOT=Path(__file__).resolve().parents[2]
def build():
 out=ROOT/'public/diagnostics/ruc-codec-v1';out.mkdir(parents=True,exist_ok=True)
 raw=b''.join(i.to_bytes(2,'little') for i in range(65536));sha=lambda b:hashlib.sha256(b).hexdigest()
 legacy=bytes.fromhex('00000080ff7fffff000001003412')
 for old in out.glob('*.raw.bin'):old.unlink()
 raw_key=sha(legacy)+'.raw.bin';(out/raw_key).write_bytes(legacy);rows=[]
 for codec in ('gzip','byteplanes-gzip','delta-byteplanes-gzip'):
  manifest,wire=encode_candidate(raw,codec);key=manifest['encodedSha256']+'.'+codec+'.bin';(out/key).write_bytes(wire);rows.append({'key':key,'manifest':manifest})
 manifest={'schema':'mid.ruc.transport-canary.v1','synthetic':True,'productionEnabled':False,'pattern':'all-int16-little-endian','raw':{'key':raw_key,'bytes':len(legacy),'sha256':sha(legacy)},'candidates':rows}
 data=(json.dumps(manifest,separators=(',',':'),sort_keys=True)+'\n').encode();(out/'index.json').write_bytes(data)
 config='// Generated by tools/ruc/build_lossless_transport_canary.py.\nexport const CANARY_MANIFEST='+data.decode().strip()+';\nexport const CANARY_MANIFEST_SHA='+json.dumps(sha(data))+';\n'
 (ROOT/'tools/ruc/lossless_canary_manifest.generated.mjs').write_text(config)
 for name in ('lossless_canary_manifest.generated.mjs','lossless_candidate_decoder.mjs','lossless_transport_canary.mjs'):
  (out/name).write_bytes((ROOT/'tools/ruc'/name).read_bytes())
 print('Synthetic canary only:',sum(p.stat().st_size for p in out.iterdir()),'bytes')
if __name__=='__main__':build()
